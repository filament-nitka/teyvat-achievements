def q(name):
    name = name.strip().strip('"').strip()
    ru = RU_NAMES.get(name)
    return f"«{ru}»" if ru else f"«{name}»"

def names_list(s):
    parts = [p for p in re.split(r",\s*(?:and\s+)?|\s+and\s+", s.strip().rstrip(".")) if p.strip()]
    qs = [q(p) for p in parts]
    return qs[0] if len(qs) == 1 else ", ".join(qs[:-1]) + " и " + qs[-1]

def auto(h):
    h = h.strip()
    m = re.fullmatch(r"Earned during (.+?)\.?", h)
    if m: return f"Выдаётся по ходу задания {q(m.group(1))}."
    m = re.fullmatch(r"Complete the Hidden Exploration Objective (.+?\.\.\.|.+?)\.?", h)
    if m: return f"Выполните скрытую исследовательскую цель {q(m.group(1))}."
    m = re.fullmatch(r"Complete (?:the )?Post-Quest Dialogue of (.+?)\.?", h)
    if m: return f"Поговорите с персонажами после задания {q(m.group(1))}."
    m = re.fullmatch(r'Complete (?:World Quest |Archon Quest )?([A-Z"][^.]*?)\.?"?', h)
    if m and not re.search(r"\b(all|the \d|every)\b", m.group(1)):
        return f"Пройдите задание {q(m.group(1))}."
    return None

